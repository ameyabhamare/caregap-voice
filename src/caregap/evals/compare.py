"""Claude vs the local model on the same evals (Phase 11): ``make eval-compare``.

    python -m caregap.evals.compare [--model claude-sonnet-5-5] [--precheck-only]

1. Precheck: 5 scripts and 3 callback questions on Claude; their cost, from the ledger,
   is projected to the full run. If the projection exceeds the budget left under
   LLM_BUDGET_USD (or ``--max-usd``), nothing more is spent.
2. The script suite's configurations (same members as ``make eval``) and every golden
   callback question, generated by Claude. The judge stays on the local model so both
   sides are scored by the same judge; reading level and compliance rules are code.
3. The local side is the latest promoted ``eval-suite`` run and the latest local
   ``rag-evals`` run per customer. Nothing is promoted or re-tagged: this is a provider
   comparison, logged to its own MLflow experiment, ``provider-compare``.

Writes docs/results/claude-vs-local.md. Every Claude call goes through the ledger.
"""

from __future__ import annotations

import argparse
import json
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from decimal import Decimal
from pathlib import Path

EXPERIMENT = "provider-compare"
REPORT = Path("docs/results/claude-vs-local.md")
PRECHECK_SCRIPTS = 5
PRECHECK_QUESTIONS = 3
SCRIPT_ROWS = (
    ("first_attempt_pass_rate", "Compliant on the first attempt", "pct"),
    ("final_pass_rate", "Compliant after one revision", "pct"),
    ("judge_all_pass_rate", "Judge (local): all criteria pass", "pct"),
    ("reading_ok_rate", "Reading grade 8 or below", "pct"),
    ("latency_p50_s", "Latency per script, p50", "s"),
    ("latency_p95_s", "Latency per script, p95", "s"),
)
QA_ROWS = (
    ("answer_accuracy", "Answerable questions answered correctly", "pct"),
    ("hallucination_rate", "Spoken hallucinations", "pct"),
    ("over_refusal_rate", "Over-refusals", "pct"),
    ("raw_hallucination_rate", "Hallucinations before the grounding check", "pct"),
    ("refusal_accuracy", "Medical/off-topic questions handed off", "pct"),
    ("latency_p50_s", "Latency per answer, p50", "s"),
)


@dataclass(frozen=True)
class Projection:
    per_script: Decimal
    per_question: Decimal
    scripts: int
    questions: int

    @property
    def total(self) -> Decimal:
        return self.per_script * self.scripts + self.per_question * self.questions


def _fmt(value: float | None, kind: str) -> str:
    if value is None:
        return "-"
    return f"{value:.1%}" if kind == "pct" else f"{value:.1f} s"


def comparison_markdown(
    model: str, local_model: str, scripts: Mapping[str, tuple[Mapping[str, float],
    Mapping[str, float]]], qa: Mapping[str, tuple[Mapping[str, float], Mapping[str, float]]],
    cost: Mapping[str, Decimal], messages: Mapping[str, int],
) -> str:  # fmt: skip
    """``scripts``/``qa``: name -> (local metrics, Claude metrics)."""
    out = [
        f"# {model} vs local {local_model}",
        "",
        "Same members, prompts (production alias), golden questions and checks on both "
        "sides; the LLM judge is the local model for both. Synthetic data only. Generated "
        "by `make eval-compare`.",
        "",
        "## Outreach scripts",
    ]
    for name, (local, claude) in scripts.items():
        out += ["", f"### {name}", "", f"| | local | {model} |", "|---|---|---|"]
        out += [f"| {label} | {_fmt(local.get(k), kind)} | {_fmt(claude.get(k), kind)} |"
                for k, label, kind in SCRIPT_ROWS]  # fmt: skip
    out += ["", "## Callback questions"]
    for name, (local, claude) in qa.items():
        out += ["", f"### {name}", "", f"| | local | {model} |", "|---|---|---|"]
        out += [f"| {label} | {_fmt(local.get(k), kind)} | {_fmt(claude.get(k), kind)} |"
                for k, label, kind in QA_ROWS]  # fmt: skip
    total = sum(cost.values(), Decimal(0))
    n = sum(messages.values())
    out += ["", "## Cost (from the ledger)", "", "| | Claude | local |", "|---|---|---|"]
    for part, usd in cost.items():
        per = usd / messages[part] if messages.get(part) else Decimal(0)
        out.append(f"| {part}: {messages.get(part, 0)} messages, ${per:.4f} each | "
                   f"${usd:.2f} | $0.00 |")  # fmt: skip
    out.append(f"| **Total** ({n} messages) | **${total:.2f}** | **$0.00** |")
    return "\n".join(out) + "\n"


def _local_baselines(tracking_uri: str) -> tuple[dict[str, dict[str, float]],
                                                 dict[str, dict[str, float]], str]:  # fmt: skip
    from mlflow.tracking import MlflowClient

    from caregap.evals import rag, suite

    client = MlflowClient(tracking_uri)
    scripts: dict[str, dict[str, float]] = {}
    model = "?"
    exp = client.get_experiment_by_name(suite.EXPERIMENT)
    if exp is not None:
        newest = ["attributes.start_time DESC"]
        parents = client.search_runs(
            [exp.experiment_id], "tags.promoted = 'true'", order_by=newest, max_results=1
        )
        if parents:
            model = parents[0].data.params.get("model", "?")
            children = client.search_runs(
                [exp.experiment_id], f"tags.mlflow.parentRunId = '{parents[0].info.run_id}'"
            )
            scripts = {r.data.tags.get("config", r.info.run_name): dict(r.data.metrics)
                       for r in children}  # fmt: skip
    qa: dict[str, dict[str, float]] = {}
    exp = client.get_experiment_by_name(rag.EXPERIMENT)
    if exp is not None:
        runs = client.search_runs(
            [exp.experiment_id], "params.provider = 'ollama'",
            order_by=["attributes.start_time DESC"], max_results=50,
        )  # fmt: skip
        for r in runs:
            qa.setdefault(r.data.params["customer"], dict(r.data.metrics))
    return scripts, qa, model


def main(argv: Sequence[str] | None = None) -> int:
    import mlflow

    from caregap.config import get_settings
    from caregap.customers import load_all
    from caregap.evals import rag, rules, suite
    from caregap.evals.judge import Judge
    from caregap.llm.embeddings import LangChainEmbeddings
    from caregap.llm.factory import build_client, build_embeddings
    from caregap.outreach.generate import ScriptGenerator
    from caregap.outreach.store import OutreachStore
    from caregap.prompts import MlflowPromptStore
    from caregap.rag.agent import CallbackAgent, token_limits
    from caregap.rag.store import BenefitRetriever, ChunkStore

    ap = argparse.ArgumentParser(prog="python -m caregap.evals.compare")
    ap.add_argument("--model", default="claude-sonnet-5-5")
    ap.add_argument("--year", type=int, default=2025)
    ap.add_argument("--max-usd", type=Decimal, help="spend ceiling (default: budget left)")
    ap.add_argument("--precheck-only", action="store_true")
    args = ap.parse_args(argv)

    local = get_settings()
    if local.anthropic_api_key is None:
        raise SystemExit("[compare] ANTHROPIC_API_KEY is not set (environment settings or .env)")
    remote = local.model_copy(update={"llm_provider": "claude", "claude_model": args.model})
    claude = build_client(remote)
    judge = Judge(build_client(local.model_copy(update={"llm_provider": "ollama"})),
                  MlflowPromptStore(local.mlflow_tracking_uri))  # fmt: skip
    prompts = MlflowPromptStore(local.mlflow_tracking_uri)
    customers = load_all(local.customers_dir)
    members = OutreachStore(local.database_url)
    chunks = ChunkStore(local.database_url)
    emb = LangChainEmbeddings(build_embeddings(local), purpose="eval-compare")

    def generators(customer: str) -> dict[str, ScriptGenerator]:
        c = customers[customer]
        return {lang: ScriptGenerator(claude, prompts, c.profile(lang), max_output_tokens=4000)
                for lang in c.languages}  # fmt: skip

    def agent() -> CallbackAgent:
        return CallbackAgent(
            claude, prompts, customers,
            lambda c: BenefitRetriever(store=chunks, embeddings=emb, customer=c),
            **token_limits("claude"),
        )  # fmt: skip

    ledger = claude.ledger
    cases = {
        cfg.name: rules.sample_cases(
            local.database_url, customers[cfg.customer], args.year, cfg.n, cfg.language
        )
        for cfg in suite.CONFIGS
    }
    golden = {c: rag.load_golden(c) for c in customers}

    # 1. Precheck.
    start = ledger.committed_usd()
    first = suite.CONFIGS[0]
    rules.run(generators(first.customer), members, cases[first.name][:PRECHECK_SCRIPTS])
    mid = ledger.committed_usd()
    g = golden[first.customer]
    sample = g.model_copy(update={"items": g.items[:PRECHECK_QUESTIONS]})
    rag.run(agent(), sample, rag.documents(first.customer, customers))
    end = ledger.committed_usd()
    p = Projection(
        per_script=(mid - start) / PRECHECK_SCRIPTS,
        per_question=(end - mid) / PRECHECK_QUESTIONS,
        scripts=sum(len(c) for c in cases.values()),
        questions=sum(len(x.items) for x in golden.values()),
    )
    ceiling = args.max_usd if args.max_usd is not None else ledger.remaining_usd()
    print(f"[compare] precheck spent ${end - start:.4f}: ${p.per_script:.4f}/script, "
          f"${p.per_question:.4f}/question -> full run ~${p.total:.2f} "
          f"({p.scripts} scripts, {p.questions} questions); ceiling ${ceiling:.2f}")  # fmt: skip
    if p.total > ceiling:
        print("[compare] projected cost is over the ceiling: stopping (use a smaller model, "
              "--max-usd, or raise LLM_BUDGET_USD)")  # fmt: skip
        return 1
    if args.precheck_only:
        return 0

    # 2. The full run.
    cost: dict[str, Decimal] = {}
    messages: dict[str, int] = {}
    claude_scripts: dict[str, dict[str, float]] = {}
    for cfg in suite.CONFIGS:
        before = ledger.committed_usd()
        print(f"[compare] scripts: {cfg.name} ({len(cases[cfg.name])} members)")
        outcomes, _, metrics = suite.run_config(cases[cfg.name], generators(cfg.customer),
                                                       judge, members)  # fmt: skip
        claude_scripts[cfg.name] = metrics
        cost[f"scripts {cfg.name}"] = ledger.committed_usd() - before
        messages[f"scripts {cfg.name}"] = len(outcomes)
    claude_qa: dict[str, dict[str, float]] = {}
    for customer, gs in golden.items():
        before = ledger.committed_usd()
        print(f"[compare] callback questions: {customer} ({len(gs.items)})")
        results = rag.run(agent(), gs, rag.documents(customer, customers))
        claude_qa[customer] = rag.summarize(results)
        cost[f"callback {customer}"] = ledger.committed_usd() - before
        messages[f"callback {customer}"] = len(results)

    # 3. Compare and record.
    local_scripts, local_qa, local_model = _local_baselines(local.mlflow_tracking_uri)
    report = comparison_markdown(
        args.model, local_model,
        {n: (local_scripts.get(n, {}), m) for n, m in claude_scripts.items()},
        {n: (local_qa.get(n, {}), m) for n, m in claude_qa.items()},
        cost, messages,
    )  # fmt: skip
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(report)
    mlflow.set_tracking_uri(local.mlflow_tracking_uri)
    mlflow.set_experiment(EXPERIMENT)
    with mlflow.start_run(run_name=f"{args.model} vs {local_model}"):
        mlflow.log_params({"model": args.model, "local_model": local_model,
                           "judge": f"ollama:{local.ollama_model}"})  # fmt: skip
        for name, m in {**{f"scripts.{k}": v for k, v in claude_scripts.items()},
                        **{f"qa.{k}": v for k, v in claude_qa.items()}}.items():  # fmt: skip
            mlflow.log_metrics({f"{name}.{k}": v for k, v in m.items()})
        mlflow.log_metric("cost_usd", float(sum(cost.values(), Decimal(0))))
        mlflow.log_text(report, "report.md")
        mlflow.log_text(json.dumps({k: str(v) for k, v in cost.items()}, indent=2), "cost.json")
    print(report)
    print(f"[compare] written to {REPORT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
